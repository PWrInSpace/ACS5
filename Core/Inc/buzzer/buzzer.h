/**
 * @file    buzzer.h
 * @brief   PWM buzzer driver - CMT-8504-100-SMT-TR
 *          Hardware: PE5 -> TIM15 CH1 -> R48(1k) -> IRLML6344 gate
 *                    Buzzer driven from 3V3, flyback D20, pull-down R49(33k)
 *
 * Timer clock source: APB2 Timer clock = 150 MHz (from CubeMX clock tree)
 */

#ifndef BUZZER_H
#define BUZZER_H

#include "stm32h7xx_hal.h"
#include <stdint.h>

/* -- Public constants -------------------------------------------------------- */

/** CMT-8504 resonant frequency - check your specific unit's datasheet.
 *  Typical value is 2400 Hz. */
#define BUZZER_RESONANT_FREQ_HZ     2400U

/** APB2 Timer clock in Hz (must match CubeMX clock tree output) */
#define BUZZER_TIMER_CLOCK_HZ       150000000UL

/* -- Note struct for melody playback ----------------------------------------- */
typedef struct {
    uint16_t freq_hz;       /* 0 = REST (silence) */
    uint16_t duration_ms;
} BuzzerNote_t;

/**
 * @brief  Initialise the buzzer driver.
 *         Must be called once after MX_TIM15_Init() and before any other
 *         buzzer function.
 * @param  htim  Pointer to the TIM15 handle generated by CubeMX.
 */
void Buzzer_Init(TIM_HandleTypeDef *htim);

/**
 * @brief  Start the buzzer at its configured frequency.
 *         Safe to call repeatedly (idempotent).
 */
void Buzzer_On(void);

/**
 * @brief  Stop the buzzer immediately (PWM output driven low -> MOSFET off).
 *         Safe to call repeatedly (idempotent).
 */
void Buzzer_Off(void);

/**
 * @brief  Set the buzzer output frequency.
 * @param  freq_hz  Desired frequency in Hz (recommended: 1000-4000).
 */
void Buzzer_SetFreq(uint32_t freq_hz);

/**
 * @brief  Blocking single-note beep. Uses HAL_Delay - do NOT call from ISR.
 *         From a FreeRTOS task use osDelay manually instead.
 * @param  freq_hz      Frequency in Hz.
 * @param  duration_ms  Duration in milliseconds.
 */
void Buzzer_Beep(uint32_t freq_hz, uint32_t duration_ms);

/**
 * @brief  Non-blocking beep start for FreeRTOS tasks.
 *         Sets frequency and turns on; caller must osDelay then Buzzer_Off().
 */
void Buzzer_BeepAsync(uint32_t freq_hz);

/**
 * @brief  Play a melody from a BuzzerNote_t array, blocking via osDelay.
 *         MUST be called from a FreeRTOS task (uses osDelay internally).
 *         A 10 ms inter-note gap is inserted between notes to articulate them.
 *
 * @param  melody  Pointer to array of BuzzerNote_t.
 * @param  len     Number of notes in the array.
 */
void Buzzer_PlayMelody(const BuzzerNote_t *melody, uint16_t len);

#endif /* BUZZER_H */